#!/usr/bin/env python3
# Derives every scratch input from inputs/ok.json. Run after setup-repo.sh.
import json, copy, pathlib
here = pathlib.Path(__file__).parent
ok = json.load(open(here/'inputs/ok.json'))
sha = (here/'repo-sha.txt').read_text().strip()
def w(name, doc):
    p = here/'inputs'/name
    p.write_text(doc if isinstance(doc, str) else json.dumps(doc, indent=2) + '\n')
def mod(fn):
    d = copy.deepcopy(ok); fn(d); return d
repo = lambda d, **kw: d['meta'].__setitem__('repository', {'url': 'https://github.com/example/demo', 'revision': sha, **kw})
def src(d, *refs):
    d['components'][0]['sources'] = list(refs)

w('broken-json.json', '{ "schema_version": 1, ')
w('schema-bad.json', mod(lambda d: (d['components'][1].__setitem__('type', 'banana'),
    d['components'][0].__setitem__('colour', 'red'), d['meta'].pop('title'))))
w('out-absolute.json', mod(lambda d: d['meta'].__setitem__('output', '/tmp/x.html')))
w('out-dotdot.json', mod(lambda d: d['meta'].__setitem__('output', '../x.html')))
w('out-ext.json', mod(lambda d: d['meta'].__setitem__('output', 'x.txt')))
w('out-and-schema-bad.json', mod(lambda d: (d['meta'].__setitem__('output', '/tmp/x.html'), d['components'][1].__setitem__('type', 'banana'))))
w('dup-relationship-id.json', mod(lambda d: d['connections'].append({'id': 'web-to-api', 'from': 'api', 'to': 'web', 'label': 'x'})))
w('unknown-endpoint.json', mod(lambda d: d['connections'][0].__setitem__('to', 'ghost')))
w('profile-fail.json', mod(lambda d: d['meta'].__setitem__('engineering_profile', 'deployment-ownership')))
w('locale-xx.json', mod(lambda d: d['meta'].__setitem__('locale', 'xx')))
w('locale-enus.json', mod(lambda d: d['meta'].__setitem__('locale', 'en-US')))
w('locale-ko.json', mod(lambda d: d['meta'].__setitem__('locale', 'ko')))
w('locale-xx-badtrans.json', mod(lambda d: d['meta'].update({'locale': 'xx', 'translations': {'viewer.nope': 'x', 'nonexistent.key': 'y'}})))
w('locale-malformed.json', mod(lambda d: d['meta'].__setitem__('locale', 'EN_us')))
w('ev-ok.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'line': 1, 'end_line': 3}))))
w('ev-no-sources.json', mod(lambda d: repo(d)))
w('ev-sources-no-repository.json', mod(lambda d: src(d, {'path': 'src/a.txt', 'line': 1})))
w('ev-file-missing.json', mod(lambda d: (repo(d), src(d, {'path': 'src/nope.txt'}))))
w('ev-line-out-of-range.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'line': 5}))))
w('ev-end-line-out-of-range.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'line': 2, 'end_line': 4}))))
w('ev-line-range-invalid.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'line': 3, 'end_line': 2}))))
w('ev-line-required.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'end_line': 2}))))
w('ev-path-escape.json', mod(lambda d: (repo(d), src(d, {'path': '../a.txt'}))))
w('ev-path-invalid.json', mod(lambda d: (repo(d), src(d, {'path': '/etc/passwd'}))))
w('ev-two-bad.json', mod(lambda d: (repo(d), src(d, {'path': 'src/nope.txt'}, {'path': 'src/a.txt', 'line': 9}))))
w('ev-revision-short.json', mod(lambda d: (repo(d, revision=sha[:7]), src(d, {'path': 'src/a.txt'}))))
w('ev-revision-unavailable.json', mod(lambda d: (repo(d, revision='0'*40), src(d, {'path': 'src/a.txt'}))))
w('ev-origin-mismatch.json', mod(lambda d: (repo(d, url='https://github.com/example/other'), src(d, {'path': 'src/a.txt'}))))
w('ev-origin-case.json', mod(lambda d: (repo(d, url='https://github.com/Example/Demo.git'), src(d, {'path': 'src/a.txt'}))))
w('ev-url-fs-path.json', mod(lambda d: (repo(d, url='/Users/me/demo'), src(d, {'path': 'src/a.txt'}))))
w('ev-host-unsupported.json', mod(lambda d: (repo(d, url='https://git.example.com/example/demo'), src(d, {'path': 'src/a.txt'}))))
w('ev-host-unsupported-local-only.json', mod(lambda d: (repo(d, url='https://git.example.com/example/demo', link_mode='local-only'), src(d, {'path': 'src/a.txt'}))))
w('ev-provider-mismatch.json', mod(lambda d: (repo(d, provider='gitlab'), src(d, {'path': 'src/a.txt'}))))
w('ev-source-label-semantic.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'line': 2, 'label': 'totally unrelated claim'}))))
w('ev-localonly-selfhosted.json', mod(lambda d: (repo(d, url='https://git.example.com/example/demo', link_mode='local-only'), src(d, {'path': 'src/a.txt', 'line': 1}))))
w('ev-web-selfhosted.json', mod(lambda d: (repo(d, url='https://git.example.com/example/demo'), src(d, {'path': 'src/a.txt', 'line': 1}))))
w('ev-selfhosted-gitlab-hint.json', mod(lambda d: (repo(d, url='https://git.example.com/example/demo', provider='gitlab'), src(d, {'path': 'src/a.txt', 'line': 1}))))
w('ev-bad-link-mode.json', mod(lambda d: (repo(d, link_mode='both'), src(d, {'path': 'src/a.txt'}))))
w('ev-bad-provider.json', mod(lambda d: (repo(d, provider='bitbucket'), src(d, {'path': 'src/a.txt'}))))
w('ev-sources-empty-array.json', mod(lambda d: (repo(d), d['components'][0].__setitem__('sources', []))))
w('ev-four-sources.json', mod(lambda d: (repo(d), src(d, *[{'path': 'src/a.txt'}]*4))))
w('ev-line-zero.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'line': 0}))))
w('ev-ok-no-line.json', mod(lambda d: (repo(d), src(d, {'path': 'src/nolines.txt'}))))
w('ev-last-line-3.json', mod(lambda d: (repo(d), src(d, {'path': 'src/a.txt', 'line': 3}))))
w('ev-directory.json', mod(lambda d: (repo(d), src(d, {'path': 'src'}))))
w('locale-xx-goodtrans.json', mod(lambda d: d['meta'].update({'locale': 'xx', 'translations': {'node.focus': 'Focus {label}'}})))
w('locale-xx-placeholder-mismatch.json', mod(lambda d: d['meta'].update({'locale': 'xx', 'translations': {'node.focus': 'Focus {name}'}})))
w('locale-zh-cn-lower.json', mod(lambda d: d['meta'].__setitem__('locale', 'zh-cn')))
w('locale-xx-then-dup-id.json', mod(lambda d: (d['meta'].__setitem__('locale', 'xx'), d['connections'].append({'id': 'web-to-api', 'from': 'api', 'to': 'web', 'label': 'x'}))))
